import asyncio, os
os.environ['PLAYWRIGHT_BROWSERS_PATH']='/opt/pw-browsers'
from playwright.async_api import async_playwright
R=[]
def ok(n,c,e=''): R.append(('PASS' if c else 'FAIL',n,e)); print(('PASS' if c else 'FAIL'), n, e, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1440,'height':900}); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.add_init_script("try { localStorage.getItem('dora-consent') || localStorage.setItem('dora-consent', JSON.stringify({value:'all',at:'test'})) } catch (e) {}")
        await pg.goto('http://localhost:4173/#/merch'); await pg.wait_for_timeout(2600)
        st = pg.locator('.sticker').first; bb = await st.bounding_box()
        await pg.mouse.move(bb['x']+bb['width']/2, bb['y']+60); await pg.mouse.down()
        await pg.mouse.move(bb['x']+bb['width']/2+150, bb['y']+120, steps=10); await pg.mouse.up(); await pg.wait_for_timeout(600)
        ok('мерч: перетаскивание не открывает товар', pg.url.endswith('/merch'))
        await pg.locator('.sticker').nth(1).dispatch_event('click'); await pg.wait_for_timeout(1500)
        ok('мерч: клик открывает страницу товара', '/merch/tee' in pg.url, pg.url)
        ok('товар: заголовок вкладки', 'Футболка' in await pg.title(), await pg.title())
        href = await pg.locator('.pd-info .pd-buy').get_attribute('href'); tgt = await pg.locator('.pd-info .pd-buy').get_attribute('target')
        ok('Купить: ведёт в официальный магазин в новой вкладке', href.startswith('https://realdora.store') and tgt=='_blank', href)
        ok('товар: пояснение про покупку', await pg.locator('.pd-note').count()==1)
        ok('товар: 3 похожих', await pg.locator('.pd-card').count()==3)
        await pg.screenshot(path='/tmp/pd1.png')
        await pg.locator('.pd-card').first.dispatch_event('click'); await pg.wait_for_timeout(2500)
        ok('похожий товар открывается', '/merch/pendant' in pg.url, pg.url)
        await pg.locator('.pd-crumbs a').dispatch_event('click'); await pg.wait_for_timeout(2500)
        ok('хлебные крошки ведут в мерч', pg.url.endswith('/merch'))
        await pg.goto('http://localhost:4173/#/merch/nope'); await pg.wait_for_timeout(1000)
        ok('несуществующий товар: понятное сообщение', await pg.locator('.product--missing').count()==1)
        m = await b.new_page(viewport={'width':375,'height':740}); m.on('pageerror', lambda e: errs.append(str(e)))
        await m.add_init_script("try { localStorage.getItem('dora-consent') || localStorage.setItem('dora-consent', JSON.stringify({value:'all',at:'test'})) } catch (e) {}")
        await m.goto('http://localhost:4173/#/merch/hoodie'); await m.wait_for_timeout(2600)
        bar = await m.locator('.pd-bar').bounding_box()
        ok('телефон: панель «Купить» прибита к низу', bar and bar['y']+bar['height'] <= 740 and bar['y'] > 600, bar)
        ok('телефон: без переполнения', await m.evaluate('document.documentElement.scrollWidth - innerWidth')<=1)
        await m.evaluate('window.scrollTo(0, 2000)'); await m.wait_for_timeout(800)
        bar2 = await m.locator('.pd-bar').bounding_box()
        ok('телефон: панель остаётся при прокрутке', bar2 and abs(bar2['y']-bar['y'])<2)
        await m.evaluate('window.scrollTo(0, 0)'); await m.wait_for_timeout(500)
        await m.screenshot(path='/tmp/pd2.png')
        print('errors', errs, flush=True)
        await b.close()
asyncio.run(main())
