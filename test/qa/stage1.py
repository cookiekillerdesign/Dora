import asyncio, os
os.environ['PLAYWRIGHT_BROWSERS_PATH']='/opt/pw-browsers'
from playwright.async_api import async_playwright
def ok(n,c,e=''): print('PASS' if c else 'FAIL', n, e, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-gl=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1440,'height':900}); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.add_init_script("try { localStorage.setItem('dora-consent', JSON.stringify({value:'all'})) } catch(e) {}")
        await pg.goto('http://localhost:4173/'); await pg.wait_for_timeout(500)
        await pg.screenshot(path='/tmp/pl.png')
        ok('заставка: логотип и полоса загрузки', await pg.locator('.preloader .pl-logo').count()==1 and await pg.locator('.pl-bar').count()==1)
        await pg.wait_for_timeout(4000)
        ok('заставка уходит после загрузки', await pg.locator('.preloader').count()==0)
        await pg.mouse.move(700,400); await pg.wait_for_timeout(300)
        ok('кастомный курсор на компьютере', await pg.locator('.cursor:not(.is-hidden)').count()==1 and await pg.evaluate("getComputedStyle(document.body).cursor")=='none')
        await pg.mouse.move(760,36); await pg.wait_for_timeout(300)
        ok('курсор растёт над ссылками', await pg.locator('.cursor.is-hover').count()==1)
        H = await pg.evaluate('document.documentElement.scrollHeight-innerHeight')
        await pg.evaluate(f'window.scrollTo(0,{H}*0.5)'); await pg.wait_for_timeout(2000)
        await pg.click('.nav-mark'); await pg.wait_for_timeout(2600)
        ok('логотип в шапке: плавно к первому слайду', await pg.evaluate('scrollY')<5 and '/#/' in pg.url, round(await pg.evaluate('scrollY')))
        ok('MISS без ленты iTunes', await pg.locator('.miss-sash').count()==0)
        await pg.goto('http://localhost:4173/#/music?era=sister'); await pg.wait_for_timeout(2500)
        ok('музыка: без подвала «Дора в сети»', await pg.locator('.site-footer').count()==0)
        y1 = await pg.evaluate("document.querySelector('.player').getBoundingClientRect().top")
        await pg.evaluate("document.querySelector('.play-hint').classList.add('is-gone')"); await pg.wait_for_timeout(600)
        y2 = await pg.evaluate("document.querySelector('.player').getBoundingClientRect().top")
        await pg.click('.svc-btn--spotify'); await pg.wait_for_timeout(1500)
        y3 = await pg.evaluate("document.querySelector('.player').getBoundingClientRect().top")
        ok('плеер не прыгает (подсказка гаснет, смена сервиса)', abs(y1-y2)<1 and abs(y1-y3)<1, f'{round(y1)} {round(y2)} {round(y3)}')
        m = await b.new_page(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True)
        await m.goto('http://localhost:4173/'); await m.wait_for_timeout(4500)
        ok('телефон: без кастомного курсора', await m.locator('.cursor').count()==0)
        print('errors', errs); await b.close()
asyncio.run(main())
