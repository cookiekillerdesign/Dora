export default function Legal() {
  const { pathname } = useLocation()
  const { lang } = useLang()
  const s = useContent('settings')
  const consent = useConsent()
  const key = pathname.replace('/', '') || 'legal'
  const doc = DOCS[key] || DOCS.legal
  useEffect(() => { store.eraTarget = 0 }, [])
  useEffect(() => { document.title = `${doc.title} | дора` }, [doc])
  return (
    <div className="legal">
      <article className="legal-paper">
        <span className="legal-kicker">дора · {key === 'legal' ? 'документы' : 'документ'}</span>
        <h1 className="legal-title">{doc.title}</h1>
        <p className="legal-date">Редакция от {fmtDate(s.legalUpdated || '2026-10-13')}</p>
        {lang === 'en' && <p className="legal-en">Legal documents are provided in Russian, as required for a site addressed to users in Russia.</p>}
        {doc.body(s, consent)}
        {key !== 'legal' && <p className="legal-back"><Link to="/legal">Все документы и сведения о владельце</Link></p>}
      </article>
      <SiteFooter />
    </div>
  )
}
